-- 6. ตารางข้อมูลผู้ใช้และบุคลากร (TB_USERS)
CREATE TABLE IF NOT EXISTS public."TB_USERS" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prefix_th VARCHAR(50),          -- คำนำหน้า TH (นาย, นาง, นางสาว, นพ., พญ., ดร. ฯลฯ)
    first_name_th VARCHAR(100) NOT NULL, -- ชื่อ TH
    last_name_th VARCHAR(100) NOT NULL,  -- นามสกุล TH
    position VARCHAR(150),          -- ตำแหน่งงาน
    prefix_en VARCHAR(50),          -- คำนำหน้า EN (Mr., Mrs., Ms., Dr., MD etc.)
    first_name_en VARCHAR(100),     -- ชื่อ EN
    last_name_en VARCHAR(100),      -- นามสกุล EN
    email VARCHAR(255),             -- อีเมล
    phone VARCHAR(50),              -- เบอร์โทรศัพท์
    avatar_url TEXT,                -- รูปโปรไฟล์
    department VARCHAR(150),        -- แผนก / หน่วยงาน
    is_active BOOLEAN DEFAULT true, -- สถานะการใช้งาน
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
