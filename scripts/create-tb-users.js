const fs = require('fs');
const path = require('path');
const { Client } = require('pg');

// 1. Read .env.local
const envPath = path.resolve(__dirname, '../.env.local');
if (fs.existsSync(envPath)) {
  const lines = fs.readFileSync(envPath, 'utf8').split('\n');
  for (const line of lines) {
    const match = line.match(/^\s*([\w.-]+)\s*=\s*(.*)?\s*$/);
    if (match) {
      let value = match[2] || '';
      if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
        value = value.slice(1, -1);
      }
      process.env[match[1]] = value.trim();
    }
  }
}

const connectionString = process.env.DATABASE_URL;
const client = new Client({ connectionString });

async function run() {
  await client.connect();
  console.log('✅ Connected to:', connectionString ? connectionString.replace(/:([^:@]+)@/, ':****@') : 'NO URL');

  await client.query(`
    CREATE TABLE IF NOT EXISTS public."TB_USERS" (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      prefix_th VARCHAR(50),
      first_name_th VARCHAR(100) NOT NULL,
      last_name_th VARCHAR(100) NOT NULL,
      position VARCHAR(150),
      prefix_en VARCHAR(50),
      first_name_en VARCHAR(100),
      last_name_en VARCHAR(100),
      email VARCHAR(255),
      phone VARCHAR(50),
      avatar_url TEXT,
      department VARCHAR(150),
      is_active BOOLEAN DEFAULT true,
      created_at TIMESTAMPTZ DEFAULT now(),
      updated_at TIMESTAMPTZ DEFAULT now()
    );

    CREATE INDEX IF NOT EXISTS idx_users_name_th ON public."TB_USERS"(first_name_th, last_name_th);
    CREATE INDEX IF NOT EXISTS idx_users_is_active ON public."TB_USERS"(is_active);

    -- Enable RLS for Supabase/Remote compatibility
    ALTER TABLE public."TB_USERS" ENABLE ROW LEVEL SECURITY;
    DROP POLICY IF EXISTS "Public Read TB_USERS" ON public."TB_USERS";
    CREATE POLICY "Public Read TB_USERS" ON public."TB_USERS" FOR SELECT USING (true);
    DROP POLICY IF EXISTS "Full Access TB_USERS" ON public."TB_USERS";
    CREATE POLICY "Full Access TB_USERS" ON public."TB_USERS" FOR ALL USING (true);
  `);

  console.log('🎉 TB_USERS created successfully!');
  
  // Verify columns
  const cols = await client.query(`
    SELECT column_name, data_type 
    FROM information_schema.columns 
    WHERE table_name = 'TB_USERS'
    ORDER BY ordinal_position;
  `);
  console.log('Columns in TB_USERS:', cols.rows.map(c => `${c.column_name} (${c.data_type})`).join(', '));

  await client.end();
}

run().catch(err => {
  console.error('❌ Error creating table:', err);
  client.end();
  process.exit(1);
});
