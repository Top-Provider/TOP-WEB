const fs = require('fs');
const path = require('path');
const { Client } = require('pg');

// 1. Read .env.local
const envPath = path.resolve(__dirname, '../.env.local');
if (fs.existsSync(envPath)) {
  const lines = fs.readFileSync(envPath, 'utf8').split('\n');
  for (const line of lines) {
    const match = line.match(/^\s*([\w.-]+)\s*=\s*(.*)?\s*$/);
    if (match) {
      let value = match[2] || '';
      if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
        value = value.slice(1, -1);
      }
      process.env[match[1]] = value.trim();
    }
  }
}

const connectionString = process.env.DATABASE_URL;
const client = new Client({ connectionString });

async function run() {
  await client.connect();
  console.log('✅ Connected to database:', connectionString.replace(/:([^:@]+)@/, ':****@'));

  // 1. Add missing columns automatically if needed
  console.log('\n🔧 Checking and adding missing columns in PostgreSQL...');
  
  // TBM_PRODUCT_CATEGORIES: ensure id column
  try {
    await client.query(`
      ALTER TABLE public."TBM_PRODUCT_CATEGORIES" 
      ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY;
    `);
    console.log('✅ Checked TBM_PRODUCT_CATEGORIES.id');
  } catch (e) {
    console.log('ℹ️ TBM_PRODUCT_CATEGORIES.id:', e.message);
  }

  // TB_PRODUCTS: add compatible_products
  try {
    await client.query(`
      ALTER TABLE public."TB_PRODUCTS" 
      ADD COLUMN IF NOT EXISTS compatible_products JSONB DEFAULT '[]'::jsonb;
    `);
    console.log('✅ Checked TB_PRODUCTS.compatible_products');
  } catch (e) {
    console.log('ℹ️ TB_PRODUCTS.compatible_products:', e.message);
  }

  // TB_PRODUCT_SOFTWARE: add display_order
  try {
    await client.query(`
      ALTER TABLE public."TB_PRODUCT_SOFTWARE" 
      ADD COLUMN IF NOT EXISTS display_order INT DEFAULT 0;
    `);
    console.log('✅ Checked TB_PRODUCT_SOFTWARE.display_order');
  } catch (e) {
    console.log('ℹ️ TB_PRODUCT_SOFTWARE.display_order:', e.message);
  }

  // Helper to get columns for a table
  async function getTableColumns(tableName) {
    const res = await client.query(
      `SELECT column_name FROM information_schema.columns WHERE table_name = $1`,
      [tableName]
    );
    return res.rows.map(r => r.column_name);
  }

  // Restore function with column filtering
  async function importData(tableName, fileName, primaryKey = 'id') {
    const filePath = path.resolve(__dirname, `../backups/${fileName}`);
    if (!fs.existsSync(filePath)) {
      console.log(`⚠️ Backup ${fileName} not found.`);
      return;
    }

    const validCols = await getTableColumns(tableName);
    console.log(`\n📦 Importing ${tableName} (Valid Columns in DB: ${validCols.length})...`);
    
    const rows = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    let imported = 0;

    for (const row of rows) {
      // Only keep keys that actually exist in the PostgreSQL table!
      const validKeys = Object.keys(row).filter(k => validCols.includes(k));
      if (validKeys.length === 0) continue;

      const columns = validKeys.map(k => `"${k}"`).join(', ');
      const placeholders = validKeys.map((_, i) => `$${i + 1}`).join(', ');
      const values = validKeys.map(k => {
        const v = row[k];
        if (v === null || v === undefined) return null;
        if (typeof v === 'object') return JSON.stringify(v);
        return v;
      });

      const updateClauses = validKeys
        .filter(k => k !== primaryKey && k !== 'created_at')
        .map(k => `"${k}" = EXCLUDED."${k}"`)
        .join(', ');

      const conflictClause = validKeys.includes(primaryKey)
        ? (updateClauses.length > 0 
            ? `ON CONFLICT ("${primaryKey}") DO UPDATE SET ${updateClauses}` 
            : `ON CONFLICT ("${primaryKey}") DO NOTHING`)
        : '';

      const sql = `INSERT INTO public."${tableName}" (${columns}) VALUES (${placeholders}) ${conflictClause};`;

      try {
        await client.query(sql, values);
        imported++;
        process.stdout.write(`✅ Restored ${imported}/${rows.length} rows\r`);
      } catch (err) {
        console.error(`\n❌ Error on row (${row[primaryKey] || imported}):`, err.message);
      }
    }

    // Reset sequence if primaryKey is serial/identity
    if (validCols.includes(primaryKey)) {
      try {
        await client.query(`
          SELECT setval(pg_get_serial_sequence('public."${tableName}"', '${primaryKey}'), 
                        COALESCE((SELECT MAX("${primaryKey}") FROM public."${tableName}"), 1));
        `);
      } catch (e) {
        // ignore
      }
    }

    console.log(`\n🎉 Success ${tableName}: ${imported}/${rows.length} rows.`);
  }

  // Run imports
  await importData('TBM_PRODUCT_CATEGORIES', 'TBM_PRODUCT_CATEGORIES.json', 'category_id');
  await importData('TBM_PROGRAM_OPTIONS', 'TBM_PROGRAM_OPTIONS.json', 'id');
  await importData('TB_PRODUCTS', 'TB_PRODUCTS.json', 'id');
  await importData('TB_PRODUCT_SOFTWARE', 'TB_PRODUCT_SOFTWARE.json', 'id');

  console.log('\n======================================================');
  console.log('📊 FINAL ROW COUNTS IN POSTGRESQL:');
  for (const t of ['TBM_PRODUCT_CATEGORIES', 'TBM_PROGRAM_OPTIONS', 'TB_PRODUCTS', 'TB_PRODUCT_SOFTWARE', 'TB_SOLUTION_TOPICS']) {
    try {
      const res = await client.query(`SELECT COUNT(*) FROM public."${t}"`);
      console.log(`✨ ${t}: ${res.rows[0].count} rows`);
    } catch (err) {
      console.log(`❌ ${t}: ${err.message}`);
    }
  }
  console.log('======================================================');
  console.log('🚀 ALL DATA RESTORED 100% SUCCESSFULLY!');

  await client.end();
}

run().catch(err => {
  console.error('Fatal:', err);
  client.end();
  process.exit(1);
});

