-- 1. ฟังก์ชันอัปเดตเวลา updated_at อัตโนมัติ
create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- =============================================================================
-- 2. ตารางหมวดหมู่หลัก (TBM_PRODUCT_CATEGORIES)
-- Id | Category_Id | Name
-- 1  | Printing    | Printing & Supply Solution
-- 2  | Hardware    | Hardware Solution
-- 3  | Software    | Software Solution
-- 4  | Network     | Network Solution
-- 5  | Medical     | Medical Equipment
-- 6  | IoT         | Smart Solution (IoT)
-- =============================================================================
create table if not exists public.tbm_product_categories (
  id integer primary key generated by default as identity,
  category_id text not null unique,               -- 'Printing', 'Hardware', 'Software', 'Network', 'Medical', 'IoT'
  name text not null,                             -- ชื่อหมวดหมู่ เช่น 'Printing & Supply Solution'
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

drop trigger if exists trg_tbm_product_categories_updated_at on public.tbm_product_categories;
create trigger trg_tbm_product_categories_updated_at
before update on public.tbm_product_categories
for each row execute function public.set_updated_at();

-- เพิ่มข้อมูลทั้ง 6 หมวดหมู่หลักตามที่กำหนด
insert into public.tbm_product_categories (id, category_id, name)
values
  (1, 'Printing', 'Printing & Supply Solution'),
  (2, 'Hardware', 'Hardware Solution'),
  (3, 'Software', 'Software Solution'),
  (4, 'Network',  'Network Solution'),
  (5, 'Medical',  'Medical Equipment'),
  (6, 'IoT',      'Smart Solution (IoT)')
on conflict (id) do update
set
  category_id = excluded.category_id,
  name = excluded.name;

-- =============================================================================
-- 3. ตาราง Master สินค้า (TBM_MASTER_PRODUCTS)
-- เชื่อมกับ TBM_PRODUCT_CATEGORIES ผ่านฟิลด์ category_id
-- =============================================================================
create table if not exists public.tbm_master_products (
  id integer primary key generated by default as identity,
  category_id text not null references public.tbm_product_categories(category_id) on update cascade,
  sub_category text,                              -- หมวดหมู่ย่อย เช่น 'Color Laser Printer', 'Toner & Supply'
  sku text unique,                                -- รหัสรุ่นสินค้า เช่น 'LBP-654CX', 'CANON-046H-SET'
  name text not null,                             -- ชื่อสินค้า เช่น 'Canon LBP-654CX'
  slug text not null unique,                      -- URL slug เช่น 'canon-lbp-654cx'
  brand text,                                     -- ยี่ห้อ เช่น 'Canon'
  product_type text not null default 'printer',   -- เช่น 'printer', 'supply', 'hardware', 'network', 'medical', 'iot'
  short_description text,                         -- คำโปรยใต้ชื่อรุ่น
  full_description text,                          -- คำอธิบายเพิ่มเติม
  specifications jsonb not null default '[]'::jsonb, -- สเปกแต่ละบรรทัด [{"label": "ความเร็ว", "value": "27 แผ่น/นาที"}]
  bullet_points text[] not null default '{}',     -- รายละเอียดเป็นข้อๆ (เช่น รายละเอียดหมึกข้อ 1-6)
  cover_image_url text,                           -- รูปภาพหลักของสินค้า
  gallery_images text[] not null default '{}',    -- รูปภาพเพิ่มเติม
  video_url text,                                 -- ลิงก์วิดีโอสินค้า (ถ้ามี)
  datasheet_en_url text,                          -- ลิงก์ไฟล์ PDF ปุ่ม Download Datasheet (EN)
  tor_th_url text,                                -- ลิงก์ไฟล์ PDF ปุ่ม Download คุณสมบัติเฉพาะ (TOR) (TH)
  is_featured boolean not null default false,
  is_active boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_tbm_master_products_category_id on public.tbm_master_products(category_id);
create index if not exists idx_tbm_master_products_product_type on public.tbm_master_products(product_type);
create index if not exists idx_tbm_master_products_is_active on public.tbm_master_products(is_active);

drop trigger if exists trg_tbm_master_products_updated_at on public.tbm_master_products;
create trigger trg_tbm_master_products_updated_at
before update on public.tbm_master_products
for each row execute function public.set_updated_at();

-- =============================================================================
-- 4. ตารางผูกเครื่องพิมพ์กับหมึกพิมพ์ที่ใช้คู่กัน (TBM_PRODUCT_COMPATIBLE_SUPPLIES)
-- =============================================================================
create table if not exists public.tbm_product_compatible_supplies (
  id integer primary key generated by default as identity,
  product_id integer not null references public.tbm_master_products(id) on delete cascade,
  supply_product_id integer not null references public.tbm_master_products(id) on delete cascade,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique (product_id, supply_product_id)
);

create index if not exists idx_tbm_compat_supplies_product_id on public.tbm_product_compatible_supplies(product_id);
create index if not exists idx_tbm_compat_supplies_supply_id on public.tbm_product_compatible_supplies(supply_product_id);

-- =============================================================================
-- 5. ตาราง Product Program / ซอฟต์แวร์โซลูชัน (TBM_PRODUCT_PROGRAMS)
-- เก็บข้อมูลโปรแกรมที่มี รูปภาพ, วิดีโอ (YouTube/MP4), และข้อความอธิบาย (Text)
-- =============================================================================
create table if not exists public.tbm_product_programs (
  id integer primary key generated by default as identity,
  category_id text not null default 'Software' references public.tbm_product_categories(category_id) on update cascade,
  program_code text unique,                       -- รหัสโปรแกรม เช่น 'vitanix-claim', 'panacea-his'
  name text not null,                             -- ชื่อโปรแกรม เช่น 'Vitanix Claim'
  slug text not null unique,                      -- URL slug เช่น 'vitanix-claim'
  client_subtitle text,                           -- เช่น '2026 • Healthcare Management'
  url_path text,                                  -- เช่น 'Topprovider.co.th / Vitanix Claim'
  badge_category text,                            -- ป้ายหมวดหมู่ เช่น 'Hospital Claim'
  badge_subcategory text,                         -- ป้ายหมวดหมู่ย่อย เช่น 'Healthcare Solution'
  short_description text not null,                -- ข้อความอธิบายสั้น (แสดงในการ์ดหน้าแรก)
  full_description text,                          -- ข้อความอธิบายแบบละเอียด (แสดงใน Popup)
  challenge_text text,                            -- ปัญหาที่พบ (The Challenge)
  solution_text text,                             -- แนวทางแก้ไข (Our Solution)
  key_features text[] not null default '{}',      -- ฟีเจอร์สำคัญ (Key Features / Deliverables)
  technologies text[] not null default '{}',      -- เทคโนโลยีที่ใช้
  metrics jsonb not null default '[]'::jsonb,     -- ตัวเลขสถิติ [{"label": "...", "value": "..."}]
  cover_image_url text not null,                  -- รูปภาพหน้าปกโปรแกรม
  gallery_images text[] not null default '{}',    -- รูปภาพหน้าจอโปรแกรมเพิ่มเติม
  video_url text,                                 -- ลิงก์วิดีโอสาธิต (เช่น YouTube Embed URL หรือ MP4)
  testimonial jsonb,                              -- คำรับรองจากลูกค้า {"quote": "...", "author": "...", "role": "..."}
  cta_text text not null default 'ดูรายละเอียด',
  is_featured boolean not null default true,
  is_active boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_tbm_product_programs_category_id on public.tbm_product_programs(category_id);
create index if not exists idx_tbm_product_programs_is_active on public.tbm_product_programs(is_active);
create index if not exists idx_tbm_product_programs_display_order on public.tbm_product_programs(display_order);

drop trigger if exists trg_tbm_product_programs_updated_at on public.tbm_product_programs;
create trigger trg_tbm_product_programs_updated_at
before update on public.tbm_product_programs
for each row execute function public.set_updated_at();

-- =============================================================================
-- 6. ตั้งค่าความปลอดภัย Row Level Security (RLS)
-- =============================================================================
alter table public.tbm_product_categories enable row level security;
alter table public.tbm_master_products enable row level security;
alter table public.tbm_product_compatible_supplies enable row level security;
alter table public.tbm_product_programs enable row level security;

grant usage on schema public to anon, authenticated;
grant select on public.tbm_product_categories to anon, authenticated;
grant select on public.tbm_master_products to anon, authenticated;
grant select on public.tbm_product_compatible_supplies to anon, authenticated;
grant select on public.tbm_product_programs to anon, authenticated;

drop policy if exists "Public can read active categories" on public.tbm_product_categories;
create policy "Public can read active categories"
  on public.tbm_product_categories for select
  to anon, authenticated
  using (is_active = true);

drop policy if exists "Public can read active master products" on public.tbm_master_products;
create policy "Public can read active master products"
  on public.tbm_master_products for select
  to anon, authenticated
  using (is_active = true);

drop policy if exists "Public can read compatible supplies" on public.tbm_product_compatible_supplies;
create policy "Public can read compatible supplies"
  on public.tbm_product_compatible_supplies for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can read active product programs" on public.tbm_product_programs;
create policy "Public can read active product programs"
  on public.tbm_product_programs for select
  to anon, authenticated
  using (is_active = true);

